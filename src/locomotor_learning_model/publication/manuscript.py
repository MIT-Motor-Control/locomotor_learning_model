def validate_manuscript(
    manuscript: Path, data_root: Path, results_root: Path, output: Path
) -> dict:
    if sha256(manuscript) != MANUSCRIPT_SHA256:
        raise ValueError(
            "This PDF differs from the audited final manuscript. Update the reviewed claim reference first."
        )
    for source in (data_root, results_root):
        if output.resolve().is_relative_to(source.resolve()) or source.resolve().is_relative_to(
            output.resolve()
        ):
            raise ValueError(
                "Place manuscript validation outside the input and reproduction directories."
            )
    if output.exists() and any(output.iterdir()):
        raise ValueError("Choose an empty manuscript-validation output directory.")
    reproduction = verify_reproduction(data_root, results_root)
    claims = numerical_claims(results_root, reproduction)
    limitations = [
        dict(item, evidence="Manual audit of this exact PDF and the supplied analysis")
        for item in AUDITED_LIMITATIONS
    ]
    report = {
        "schema_version": 1,
        "created_at": utc_now(),
        "manuscript_title": MANUSCRIPT_TITLE,
        "manuscript_sha256": MANUSCRIPT_SHA256,
        "reproduction_report_sha256": sha256(results_root / "report.json"),
        "status": "matched" if all(item["status"] == "matched" for item in claims + limitations) else "incomplete",
        "claims": claims,
        "audited_limitations": limitations,
        "counts": dict(Counter(item["status"] for item in claims + limitations)),
        "scope": "Numerical claims checked to printed precision; see docs/reproducibility.md for coverage and limits. This is not raw-to-paper or pixel-identical certification.",
    }
    output.mkdir(parents=True, exist_ok=True)
    (output / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    lines = [
        "# Final manuscript comparison",
        "",
        report["scope"],
        "",
        f"PDF SHA-256: `{MANUSCRIPT_SHA256}`.",
        "",
        "| Claim | PDF page | Status | Evidence |",
        "|---|---:|---|---|",
    ]
    for item in claims + limitations:
        evidence = (
            item.get("reason") or f"Observed {item['observed']}; manuscript {item['manuscript']}."
        )
        lines.append(f"| {item['claim']} | {item['page']} | {item['status']} | {evidence} |")
    lines += [
        "",
        "Exit code 2 means that manuscript agreement is incomplete. Do not change data or model settings simply to remove a discrepancy.",
        "",
    ]
    (output / "report.md").write_text("\n".join(lines))
    return report
